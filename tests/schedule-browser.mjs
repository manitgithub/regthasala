import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const base = 'http://127.0.0.1:8080';
const token = Date.now().toString(36);
const access = readFileSync('runtime/dev-access.txt', 'utf8');
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const failures = [];
page.on('pageerror', e => failures.push(e.message));
page.on('response', r => { if (r.status() >= 500) failures.push(r.url()); });
mkdirSync('tests/artifacts', { recursive: true });
try {
  await page.goto(`${base}/site/staff-login`);
  await page.getByLabel('อีเมล', { exact: true }).fill(access.match(/Email: (.+)/)[1]);
  await page.getByLabel('รหัสผ่าน', { exact: true }).fill(access.match(/Password: (.+)/)[1]);
  await page.getByRole('button', { name: 'เข้าสู่ระบบ', exact: true }).click();
  await page.waitForURL('**/admin/index');
  await page.goto(`${base}/admin/edit?entity=round`);
  await page.locator('#exam-type').selectOption({ index: 1 });
  await page.getByLabel('ชื่อรอบสอบ', { exact: true }).fill(`TEST-SCHEDULE-${token}`);
  await page.getByLabel('เปิดรับสมัคร', { exact: true }).fill('2027-01-01T08:00');
  await page.getByLabel('ปิดรับสมัคร', { exact: true }).fill('2027-01-15T16:00');
  await page.getByLabel('สิ้นสุดชำระเงิน', { exact: true }).fill('2027-01-16T16:00');
  await page.getByLabel('เพิ่มจากรายการที่ใช้บ่อย', { exact: true }).selectOption('วันสอบ');
  const first = page.locator('[data-schedule-row]').first();
  await first.getByLabel('วันและเวลาเริ่ม', { exact: true }).fill('2027-01-20T09:00');
  await first.getByLabel('วันและเวลาสิ้นสุด (ถ้ามี)', { exact: true }).fill('2027-01-19T09:00');
  await first.getByLabel('สถานที่ / ช่องทาง', { exact: true }).fill('อาคาร A');
  await first.getByLabel('รายละเอียดเพิ่มเติม', { exact: true }).fill('มาถึงก่อนเวลา 30 นาที');
  await page.getByLabel('เพิ่มจากรายการที่ใช้บ่อย', { exact: true }).selectOption('ประกาศผลสอบ');
  await page.locator('[data-schedule-row]').last().getByLabel('วันและเวลาเริ่ม', { exact: true }).fill('2027-01-25T09:00');
  await page.getByRole('button', { name: 'บันทึกรอบสอบ', exact: true }).click();
  assert(await page.getByText('วันสิ้นสุดต้องไม่ก่อนวันเริ่ม', { exact: true }).isVisible());
  assert.equal(await page.locator('[data-schedule-row]').count(), 2, 'Rows retained after validation failure');
  await page.locator('[data-schedule-row]').first().getByLabel('วันและเวลาสิ้นสุด (ถ้ามี)', { exact: true }).fill('2027-01-20T12:00');
  await page.getByRole('button', { name: 'บันทึกรอบสอบ', exact: true }).click();
  await page.waitForURL('**/admin/round?id=*');
  const roundUrl = page.url();
  await page.getByRole('link', { name: 'แก้ไขรอบสอบ', exact: true }).click();
  const editorUrl = page.url();
  assert.equal(await page.locator('[data-schedule-row]').count(), 2);
  assert.equal(await page.locator('[data-schedule-row]').first().getByLabel('สถานที่ / ช่องทาง', { exact: true }).inputValue(), 'อาคาร A');
  await page.screenshot({ path: 'tests/artifacts/schedule-editor-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'tests/artifacts/schedule-editor-mobile.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  const stale = await context.newPage();
  await stale.goto(editorUrl);
  await page.locator('[data-schedule-row]').last().getByRole('button', { name: 'ลบกำหนดการ', exact: true }).click();
  await page.getByRole('button', { name: 'บันทึกรอบสอบ', exact: true }).click();
  await page.waitForURL(roundUrl);
  await stale.getByLabel('ชื่อรอบสอบ', { exact: true }).fill(`WRONG-SCHEDULE-${token}`);
  await stale.getByRole('button', { name: 'บันทึกรอบสอบ', exact: true }).click();
  assert(await stale.getByText('กำหนดการถูกแก้ไขจากอีกหน้าต่าง กรุณาเปิดรอบสอบใหม่ก่อนบันทึก', { exact: true }).isVisible());
  await page.goto(roundUrl);
  assert(await page.getByRole('heading', { name: `TEST-SCHEDULE-${token}`, exact: true }).isVisible(), 'Conflicting save must not update round either');
  await page.goto(editorUrl);
  assert.equal(await page.locator('[data-schedule-row]').count(), 1);
  await page.locator('[data-schedule-row]').first().getByRole('button', { name: 'ลบกำหนดการ', exact: true }).click();
  await page.getByRole('button', { name: 'บันทึกรอบสอบ', exact: true }).click();
  await page.waitForURL(roundUrl);
  await page.goto(editorUrl);
  assert.equal(await page.locator('[data-schedule-row]').count(), 0);
  assert.equal(failures.length, 0, failures.join('\n'));
  console.log('Schedule checks passed: one-page creation, date validation, saved ranges/venues, row deletion, empty schedule, concurrent edit protection and mobile layout.');
} finally {
  await browser.close();
  execFileSync('php', ['tests/cleanup.php', token], { stdio: 'inherit' });
}
