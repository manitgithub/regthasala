import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8080';
const credentials = readFileSync('runtime/dev-access.txt', 'utf8');
const email = credentials.match(/Email: (.+)/)[1];
const password = credentials.match(/Password: (.+)/)[1];
mkdirSync('tests/artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true });
const admin = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await admin.newPage();
const failures = [];
const unique = Date.now().toString(36);
const idBase = '9' + String(Date.now()).slice(-11);
const idCheck = (11 - [...idBase].reduce((sum, digit, i) => sum + Number(digit) * (13 - i), 0) % 11) % 10;
const nationalId = idBase + idCheck;
page.on('pageerror', error => failures.push(error.message));
page.on('response', response => { if (response.status() >= 500) failures.push(`${response.status()} ${response.url()}`); });

try {
  await page.goto(`${base}/admin/index`);
  await page.waitForURL('**/site/staff-login');
  await page.getByLabel('อีเมล', { exact: true }).fill(email);
  await page.getByLabel('รหัสผ่าน', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'เข้าสู่ระบบ', exact: true }).click();
  await page.waitForURL('**/admin/index');
  await page.getByRole('row').filter({ hasText: 'รอบที่ 1 · รับสมัครทั่วไป' }).getByRole('link', { name: 'จัดการ', exact: true }).click();
  await page.waitForURL('**/admin/round?id=*');
  const roundUrl = page.url();
  await page.screenshot({ path: 'tests/artifacts/round-desktop.png', fullPage: true });

  await page.getByRole('link', { name: 'เพิ่มวิชา', exact: true }).click();
  await page.getByLabel('รหัสวิชา', { exact: true }).fill(`TEST-${unique}`);
  await page.getByLabel('ชื่อรายวิชา', { exact: true }).fill(`วิชาทดสอบ ${unique}`);
  await page.getByLabel('เริ่มสอบ', { exact: true }).fill('2027-01-15T09:00');
  await page.getByLabel('สิ้นสุดสอบ', { exact: true }).fill('2027-01-15T10:30');
  await page.getByLabel('จำนวนที่นั่ง', { exact: true }).fill('25');
  await page.getByLabel('ค่าสมัคร (บาท)', { exact: true }).fill('125.50');
  await page.getByLabel('สนามสอบ / อาคาร / ห้อง', { exact: true }).fill('อาคารทดสอบ ห้อง 101');
  await page.getByRole('button', { name: 'บันทึกรายวิชา', exact: true }).click();
  await page.waitForURL(roundUrl);
  assert(await page.getByRole('link', { name: `วิชาทดสอบ ${unique}`, exact: true }).isVisible());
  await page.reload();
  assert(await page.getByRole('link', { name: `วิชาทดสอบ ${unique}`, exact: true }).isVisible());

  await page.getByRole('link', { name: 'เพิ่มกำหนดการ', exact: true }).click();
  await page.getByRole('button', { name: 'เพิ่มกำหนดการ', exact: true }).click();
  const schedule = page.locator('[data-schedule-row]').last();
  await schedule.getByLabel('ชื่อกำหนดการ', { exact: true }).fill(`ตรวจเอกสาร ${unique}`);
  await schedule.getByLabel('วันและเวลาเริ่ม', { exact: true }).fill('2026-11-28T16:00');
  await schedule.getByLabel('สถานที่ / ช่องทาง', { exact: true }).fill('ห้องทะเบียน');
  await page.getByRole('button', { name: 'บันทึกรอบสอบ', exact: true }).click();
  await page.waitForURL(roundUrl);
  assert(await page.getByText(`ตรวจเอกสาร ${unique}`, { exact: true }).isVisible());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'tests/artifacts/round-mobile.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page must not overflow');

  const applicant = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const applicantPage = await applicant.newPage();
  await applicantPage.goto(`${base}/site/register`);
  await applicantPage.waitForURL('**/site/index');
  assert.equal(await applicantPage.getByRole('link', { name: 'สมัครสมาชิก', exact: true }).count(), 0, 'Standalone membership links removed');
  await applicantPage.goto(`${base}/site/login`);
  assert.equal(await applicantPage.getByRole('link', { name: 'สมัครสมาชิก', exact: true }).count(), 0);
  const csrf = await applicantPage.locator('input[name="_csrf"]').inputValue();
  const legacyResponse = await applicant.request.post(`${base}/site/register`, { form: { _csrf: csrf } });
  assert(new URL(legacyResponse.url()).pathname === '/site/index', 'Legacy membership POST must redirect without registering');
  const roundId = new URL(roundUrl).searchParams.get('id');
  await applicantPage.goto(`${base}/applicant/apply?id=${roundId}`);
  assert(applicantPage.url().includes('/applicant/apply'), 'Guest must reach application without login');
  await applicantPage.getByLabel('ชื่อและนามสกุล', { exact: true }).fill(`ผู้สมัครทดสอบระบบ ${unique}`);
  await applicantPage.getByLabel('เลขบัตรประชาชน', { exact: true }).fill(nationalId);
  await applicantPage.getByLabel('วันเกิด 8 หลัก (พ.ศ.)', { exact: true }).fill('01012540');
  await applicantPage.getByRole('button', { name: 'ยืนยันใบสมัคร', exact: true }).click();
  assert(await applicantPage.getByText('กรุณาเลือกอย่างน้อย 1 วิชา', { exact: true }).isVisible());
  await applicantPage.getByLabel('วันเกิด 8 หลัก (พ.ศ.)', { exact: true }).fill('01012540');
  await applicantPage.locator('[data-fee]').first().check();
  await applicantPage.locator('[data-fee]').nth(1).check();
  assert.equal((await applicantPage.locator('#selected-total').textContent()).trim(), '550.00');
  await applicantPage.screenshot({ path: 'tests/artifacts/applicant-desktop.png', fullPage: true });
  await applicantPage.getByRole('button', { name: 'ยืนยันใบสมัคร', exact: true }).click();
  await applicantPage.waitForURL('**/applicant/index');
  assert(await applicantPage.getByText('รวม 550.00 บาท', { exact: true }).isVisible());
  await applicantPage.goto(`${base}/admin/index`);
  assert(await applicantPage.getByText('ไม่สามารถเปิดหน้านี้ได้', { exact: true }).isVisible(), 'Applicant must not access admin');
  await applicantPage.getByRole('button', { name: 'ออกจากระบบ', exact: true }).click();
  await applicantPage.goto(`${base}/site/login`);
  await applicantPage.getByLabel('เลขบัตรประชาชน', { exact: true }).fill(nationalId);
  await applicantPage.getByLabel('วันเกิด 8 หลัก (พ.ศ.)', { exact: true }).fill('02012540');
  await applicantPage.getByRole('button', { name: 'เข้าสู่ระบบ', exact: true }).click();
  assert(await applicantPage.getByText('เลขบัตรประชาชนหรือวันเกิดไม่ถูกต้อง', { exact: true }).isVisible());
  await applicantPage.getByLabel('วันเกิด 8 หลัก (พ.ศ.)', { exact: true }).fill('01012540');
  await applicantPage.getByRole('button', { name: 'เข้าสู่ระบบ', exact: true }).click();
  await applicantPage.waitForURL('**/applicant/index');
  assert(await applicantPage.getByText('รวม 550.00 บาท', { exact: true }).isVisible());
  await applicantPage.goto(`${base}/applicant/apply?id=${roundId}`);
  await applicantPage.locator('[data-fee]').first().check();
  await applicantPage.getByRole('button', { name: 'ยืนยันใบสมัคร', exact: true }).click();
  assert(await applicantPage.getByText('คุณสมัครรอบสอบนี้แล้ว', { exact: true }).isVisible());

  const csrfResponse = await applicant.request.post(`${base}/applicant/apply?id=${roundId}`, { form: { subjects: '1' } });
  assert.equal(csrfResponse.status(), 400, 'CSRF token is required');
  assert.equal(failures.length, 0, failures.join('\n'));
  console.log('Browser checks passed: staff login, direct guest application, ID/birth-date login, wrong birth-date rejection, authorization, persisted subject/milestone creation, responsive layout, fee total, duplicate rejection and CSRF.');
} finally {
  await browser.close();
  execFileSync('php', ['tests/cleanup.php', unique], { stdio: 'inherit' });
}
