import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:8080';
const browser = await chromium.launch();
try {
  const context = await browser.newContext();
  const page = await context.newPage();
  const errors = [];
  const external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith(base)) external.push(request.url()); });
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto(`${base}/applicant/apply?id=4`);
    const query = page.getByRole('combobox', { name: 'ตำบล / อำเภอ / จังหวัด / รหัสไปรษณีย์', exact: true });
    const list = page.getByRole('listbox', { name: 'พื้นที่ที่ตรงกับคำค้น', exact: true });
    await query.fill('ท่าศาลา นครศรี');
    await list.getByRole('option').first().waitFor();
    assert(await list.getByRole('option').count() > 0);
    assert.equal(await query.getAttribute('aria-expanded'), 'true');
    assert(await list.evaluate(el => { const r = el.getBoundingClientRect(); return r.top >= 0 && r.bottom <= innerHeight; }), 'Suggestions stay within the visible viewport');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: `tests/artifacts/address-search-${width}.png` });
    await query.press('ArrowDown');
    assert(await query.getAttribute('aria-activedescendant'));
    await query.press('Enter');
    assert.equal(await page.locator('[data-address-part="subdistrict_code"]').inputValue(), '800801');
    assert.equal(await page.locator('[data-address-part="subdistrict"]').inputValue(), 'ท่าศาลา');
    assert.equal(await page.locator('[data-address-part="district"]').inputValue(), 'ท่าศาลา');
    assert.equal(await page.locator('[data-address-part="province"]').inputValue(), 'นครศรีธรรมราช');
    assert.equal(await page.locator('[data-address-part="postal_code"]').inputValue(), '80160');
    assert.equal(await query.getAttribute('aria-expanded'), 'false');
    assert.equal(await page.locator('[data-address-part="district"]').getAttribute('type'), 'hidden');
    await query.fill('สีลม');
    assert.equal(await page.locator('[data-address-part="subdistrict_code"]').inputValue(), '', 'Editing invalidates previous area selection');
    assert.equal(await query.evaluate(input => input.checkValidity()), false);
    await list.getByRole('option').first().click();
    assert((await query.inputValue()).includes('แขวงสีลม เขตบางรัก กรุงเทพมหานคร'));
    await query.fill('80160');
    await list.getByRole('option').first().waitFor();
    assert((await list.innerText()).includes('นครศรีธรรมราช'));
    await query.press('Escape');
    assert.equal(await query.getAttribute('aria-expanded'), 'false');
    await query.fill('NO-AREA-MATCH-123');
    assert(await page.getByText('ไม่พบพื้นที่ที่ตรงกับคำค้น', { exact: true }).isVisible());
  }
  assert.equal(external.length, 0, 'Address searches never send data to an external host');
  const retryContext = await browser.newContext();
  let attempts = 0;
  await retryContext.route('**/data/thai-address/address.json', route => ++attempts === 1 ? route.abort() : route.continue());
  const retryPage = await retryContext.newPage();
  await retryPage.goto(`${base}/applicant/apply?id=4`);
  await retryPage.getByRole('button', { name: 'โหลดข้อมูลอีกครั้ง', exact: true }).click();
  const retryQuery = retryPage.locator('[data-address-query]');
  await retryQuery.fill('80160');
  await retryPage.getByRole('listbox').getByRole('option').first().waitFor();
  assert(attempts >= 2, 'Failed dataset can be reloaded');
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('Thai address checks passed: single field, keyboard/touch-friendly options, Bangkok labels, postal search, stale selection clearing, local-only requests, load retry and desktop/mobile layout.');
} finally { await browser.close(); }
